#!/usr/bin/env bash
# Tak_OS · detect-hardware.sh — Detects CPU, GPU and VM host, writes hardware-detected.nix
# github.com/tak0dan/Tak_OS · GNU GPLv3
#
# Reads only sysfs, /proc and systemd-detect-virt, so it needs no extra packages.
# The output is machine-specific and untracked (see .gitignore). Re-run it after
# changing hardware or moving the install to another machine.
#
# Usage: scripts/detect-hardware.sh [OUTPUT_FILE]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:-$ROOT/hardware-detected.nix}"

# ── Virtualisation ───────────────────────────────────────────────────────────
# systemd-detect-virt prints "none" and exits 1 on bare metal, so the || guard
# keeps set -e from aborting.
vm="$(systemd-detect-virt --vm 2>/dev/null || true)"
[ -n "$vm" ] || vm="none"

case "$vm" in
  kvm|qemu)   guest="qemu";       vm_modules=(virtio_pci virtio_blk virtio_scsi virtio_net virtio_gpu) ;;
  oracle)     guest="virtualbox"; vm_modules=(vboxguest vboxsf vboxvideo) ;;
  vmware)     guest="vmware";     vm_modules=(vmw_pvscsi vmxnet3 vmwgfx) ;;
  microsoft)  guest="hyperv";     vm_modules=(hv_vmbus hv_storvsc hv_netvsc hv_utils) ;;
  none)       guest="none";       vm_modules=() ;;
  *)          guest="none";       vm_modules=() ;;   # Unknown hypervisor: no guest modules guessed.
esac

# ── CPU ──────────────────────────────────────────────────────────────────────
cpu_flags="$(grep -m1 '^flags' /proc/cpuinfo 2>/dev/null || true)"
vendor="$(grep -m1 '^vendor_id' /proc/cpuinfo 2>/dev/null | awk '{print $3}' || true)"
case "$vendor" in
  GenuineIntel) cpu="intel" ;;
  AuthenticAMD) cpu="amd" ;;
  *)            cpu="unknown" ;;
esac

# KVM is only force-loaded on bare metal: inside a guest the host owns VMX/SVM.
kernel_modules=()
if [ "$guest" = "none" ]; then
  case " $cpu_flags " in
    *" vmx "*) kernel_modules+=(kvm-intel) ;;
    *" svm "*) kernel_modules+=(kvm-amd) ;;
  esac
fi

# ── GPU ──────────────────────────────────────────────────────────────────────
# PCI class 0x03xxxx = display controller. Vendor IDs are the standard PCI IDs.
gpu_vendors=()
has_nvidia=0; has_amd=0; has_intel=0
for dev in /sys/bus/pci/devices/*; do
  [ -r "$dev/class" ] || continue
  case "$(cat "$dev/class")" in
    0x03*) ;;
    *) continue ;;
  esac
  vendor_id="$(cat "$dev/vendor")"
  case "$vendor_id" in
    0x10de) gpu_vendors+=(nvidia); has_nvidia=1 ;;
    0x1002) gpu_vendors+=(amd);    has_amd=1 ;;
    0x8086) gpu_vendors+=(intel);  has_intel=1 ;;
    0x1af4|0x1234|0x80ee|0x15ad|0x1414) gpu_vendors+=(virtual) ;;
    *)      gpu_vendors+=(other) ;;
  esac
done

# Map the hardware onto gpu.nix's profiles. Every pair produced here satisfies
# the assertions in modules/gpu.nix.
if [ "$guest" != "none" ]; then
  kernel_params="generic"; driver="none"                 # VMs use the hypervisor's display, no vendor driver
elif [ "$has_nvidia" = 1 ] && [ "$has_intel" = 1 ]; then
  kernel_params="nvidia"; driver="nvidia-prime"          # Optimus hybrid
elif [ "$has_nvidia" = 1 ]; then
  kernel_params="nvidia"; driver="nvidia"
elif [ "$has_amd" = 1 ]; then
  kernel_params="amd"; driver="amd"
elif [ "$has_intel" = 1 ]; then
  kernel_params="generic"; driver="intel"
else
  kernel_params="generic"; driver="none"
fi

# Early kernel-mode-setting modules for the detected GPU. "available" only makes
# them loadable in the initrd; nothing is force-loaded here.
gpu_modules=()
[ "$has_nvidia" = 1 ] && gpu_modules+=(nvidia nvidia_modeset nvidia_uvm nvidia_drm)
[ "$has_amd" = 1 ]    && gpu_modules+=(amdgpu)
[ "$has_intel" = 1 ]  && gpu_modules+=(i915)
initrd_modules=(${gpu_modules[@]+"${gpu_modules[@]}"} ${vm_modules[@]+"${vm_modules[@]}"})

# ── Nix output ───────────────────────────────────────────────────────────────
nix_list() {
  printf '['
  for item in "$@"; do printf ' "%s"' "$item"; done
  printf ' ]'
}

# Unique GPU vendor list (e.g. "intel nvidia").
mapfile -t uniq_gpus < <(printf '%s\n' ${gpu_vendors[@]+"${gpu_vendors[@]}"} | awk 'NF && !seen[$0]++')

tmp="$(mktemp "${OUT}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
  echo "# Tak_OS · hardware-detected.nix — generated by scripts/detect-hardware.sh"
  echo "# Machine-specific and untracked. Regenerate with: scripts/detect-hardware.sh"
  echo "# Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "{"
  echo "  cpu = \"$cpu\";"
  echo "  gpus = $(nix_list ${uniq_gpus[@]+"${uniq_gpus[@]}"});"
  echo "  guest = \"$guest\";"
  echo "  kernelParams = \"$kernel_params\";"
  echo "  driver = \"$driver\";"
  echo "  kernelModules = $(nix_list ${kernel_modules[@]+"${kernel_modules[@]}"});"
  echo "  initrdModules = $(nix_list ${initrd_modules[@]+"${initrd_modules[@]}"});"
  echo "}"
} > "$tmp"
mv "$tmp" "$OUT"
trap - EXIT

echo "Wrote $OUT"
echo "  cpu=$cpu gpus=[${uniq_gpus[*]:-none}] guest=$guest"
echo "  kernelParams=$kernel_params driver=$driver"
